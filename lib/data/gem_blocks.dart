// Extracted from the original SVG plans (the extraction script is not kept in the
// repository). The standing statues are in gem_figures.dart.
//
// Everything that stands ON the floor of a plan, in the same normalised (0..1)
// space as MapPlace.position:
//   * MapBlock  - shop / restaurant / service units, fixtures, statues, walls
//   * MapStep   - one tread of a staircase (a quad whose top is `h` high)
// Heights are fractions of the plan's short side (same unit as _heightFactor).

class MapBlock {
  const MapBlock(this.kind, this.h, this.pts, [this.placeId]);

  /// shop | food | service | fixture | desk | ledge | plinth | monument | statue | wall
  /// | rwall (a thin strip of a wall that is drawn in the plan itself)
  final String kind;
  final double h;

  /// x0,y0,x1,y1,... normalised.
  final List<double> pts;

  /// The pin that stands on this unit (it is drawn on the roof).
  final String? placeId;
}

class MapStep {
  const MapStep(this.h, this.pts);
  final double h;
  final List<double> pts;
}

